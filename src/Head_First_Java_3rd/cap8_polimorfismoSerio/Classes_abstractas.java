package Head_First_Java_3rd.cap8_polimorfismoSerio;

public class Classes_abstractas {
    /*
    Uma classe abstracta é aquela que nao se pode instanciar(criar um objecto através dela).É  útil em casos em que temos classes
    que nao sao muito específicas.

    Como criar:
    colocamos "abstract" antes da declaraçao da classe.

    ex: abstract class Canine extends Animal{}.

    NB:Uma classe abstracta deve ser herdada.Podemos usar a classe como variável de referência.

    ex: Canine c=new Canine(); -> vai dar erro

     Canine c=new Dog(); -> vai funcionar, pois c está a ser usada como variável de referência.

     NB2:As classes que podem ser instanciadas chamam-se classes concretas.
     */
}
