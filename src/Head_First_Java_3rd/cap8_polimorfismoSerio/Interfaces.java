package Head_First_Java_3rd.cap8_polimorfismoSerio;

public class Interfaces {
    /*
    Interface é uma soluçao para herança múltipla(que nao é possivel em java, uma classe ter herdar de 2 ou mais classes directamente).

    Criando uma interface:

    tipo de encapsulamento  interface nome{}

    NB:Todos os metodos na interface sao abstractos.

    ex: public interface Pet{

    public abstract void beFriendly();
    public abstract void play();
    }
    NB:Os metodos de uma interface sao implicitamente publicos e abstractos, escrever public e abstract é opcional( e nao e considerado boa práctica escrever)

    Implementando a interface:

   colocamos o implements logo depois do nome da classe.

   ex: public class Dog extends Canine implements Pet{}
   NB:Podemos implementar mais de uma interface é só separar os nomes das interfaces por vírgula.

   NB:A classe que implementa a interface deve implementar todos os metodos da interface.


     */
}
